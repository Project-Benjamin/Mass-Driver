"""Verify installed restoration bytes in a completed two-disc release.

This regenerates selected corrections from pinned retail data and compares
the actual media. It is not a gameplay or all-bugs certification.
"""
from __future__ import annotations

import argparse
from collections.abc import Callable
import hashlib
import json
from pathlib import Path

from modules.definitive.build import RetailDisc, RETAIL_SHA256, digest
from modules.definitive.options import Options
from modules.definitive.qol import patch_rewards


class RestorationAuditError(ValueError):
    pass


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _records(rows: list[dict], key: str) -> dict:
    result = {}
    for row in rows:
        name = row[key]
        if name in result:
            raise RestorationAuditError(f"Duplicate manifest/receipt record: {name}")
        result[name] = row
    return result


def verify_expected_resources(read_current: Callable[[int], bytes], expected: dict[int, bytes], manifest_rows: list[dict]) -> list[dict]:
    """Compare independently generated bytes, not merely two claimed hashes."""
    records = _records(manifest_rows, "canonical_id")
    checked = []
    for canonical, wanted in sorted(expected.items()):
        record = records.get(canonical)
        wanted_hash = _sha(wanted)
        if record is None or record.get("size") != len(wanted) or record.get("sha256") != wanted_hash:
            raise RestorationAuditError(f"Manifest replacement {canonical} differs from current restoration sources")
        actual = read_current(canonical)
        actual_hash = _sha(actual)
        if actual != wanted:
            raise RestorationAuditError(
                f"Installed resource {canonical} differs: expected {wanted_hash}, actual {actual_hash}")
        checked.append({"canonical_id": canonical, "size": len(actual),
                        "expected_sha256": wanted_hash, "installed_sha256": actual_hash,
                        "exact_bytes_match": True})
    return checked


def _verify_output(folder: Path, record: dict) -> Path:
    path = (folder / record["path"]).resolve()
    if not path.is_relative_to(folder) or path == folder:
        raise RestorationAuditError("Receipt output path escapes the release folder")
    if not path.is_file() or path.stat().st_size != record.get("size") or digest(path) != record.get("sha256"):
        raise RestorationAuditError(f"Output identity differs from completed receipt: {record['path']}")
    return path


def audit_release(folder: Path) -> dict:
    # Lazy import keeps the audit dependency out of the production builder.
    from modules.definitive.restoration import build_restoration_replacements

    folder = Path(folder).resolve()
    receipt_path = folder / "project-build.json"
    receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
    if (receipt.get("format") != "xenogears-project-build-v1"
            or receipt.get("status") != "built"
            or receipt.get("plan", {}).get("profile") != "definitive"
            or receipt.get("plan", {}).get("prepare_only")):
        raise RestorationAuditError("A completed Definitive build receipt is required")
    outputs = _records(receipt["outputs"], "path")
    required = {"definitive-build-manifest.json", "Xenogears_Definitive_CD1.bin", "Xenogears_Definitive_CD2.bin"}
    if not required <= outputs.keys():
        raise RestorationAuditError("Completed receipt is missing required paired-disc outputs")
    # Hash every recorded output, including CUE and playlist sidecars.
    verified_outputs = {name: _verify_output(folder, record) for name, record in outputs.items()}
    manifest = json.loads(verified_outputs["definitive-build-manifest.json"].read_text(encoding="utf-8"))
    if manifest.get("format") != "xenogears-definitive-build-v1":
        raise RestorationAuditError("Unsupported Definitive build manifest")
    options = Options(**manifest["options"])
    options.validate()
    result = {
        "format": "xenogears-installed-restoration-audit-v1",
        "release": receipt["plan"]["release"], "build_dir": str(folder),
        "receipt_sha256": digest(receipt_path),
        "manifest_sha256": outputs["definitive-build-manifest.json"]["sha256"],
        "options": manifest["options"], "recorded_outputs_verified": len(outputs),
        "scope": "Exact installed restoration replacements and selected XP rewards regenerated from current sources and pinned retail media.",
        "limits": ["No emulator or gameplay execution", "Does not certify every game bug or item/spell behavior",
                   "Other options are covered by completed-output identity, not independently regenerated here"],
        "gameplay_status": "untested", "all_bugs_fixed_verified": False,
        "discs": {},
    }
    for disc in (1, 2):
        original_record = receipt["sources"][f"retail_disc{disc}"]
        manifest_source = manifest["sources"][str(disc)]
        original_path = Path(original_record["path"]).resolve()
        if Path(manifest_source["path"]).resolve() != original_path:
            raise RestorationAuditError(f"Disc {disc} manifest and receipt name different source media")
        actual_hash = digest(original_path)
        expected_hash = RETAIL_SHA256[disc]
        if (actual_hash != expected_hash or original_record.get("sha256") != expected_hash
                or manifest_source.get("sha256") != expected_hash
                or original_path.stat().st_size != original_record.get("size")
                or original_path.stat().st_size != manifest_source.get("size")):
            raise RestorationAuditError(f"Disc {disc} source identity differs from pinned retail")
        original = RetailDisc(original_path, disc)
        built_name = f"Xenogears_Definitive_CD{disc}.bin"
        built = RetailDisc(verified_outputs[built_name], disc)
        expected, regeneration = {}, {}
        if options.bug_fixes:
            expected, regeneration["restoration"] = build_restoration_replacements(original.read)
        if options.double_xp:
            expected, regeneration["double_xp"] = patch_rewards(original.read, expected)
        checked = verify_expected_resources(built.read, expected, manifest["discs"][str(disc)]["replacements"])
        result["discs"][str(disc)] = {
            "retail_sha256": actual_hash, "installed_disc_sha256": outputs[built_name]["sha256"],
            "restoration_selected": options.bug_fixes, "double_xp_selected": options.double_xp,
            "resources_checked": len(checked), "resources": checked,
            "regeneration": regeneration, "exact_selected_bytes_verified": True,
            "gameplay_status": "untested",
        }
    result["exact_selected_bytes_verified"] = True
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = audit_release(args.build_dir)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"release": result["release"], "exact_selected_bytes_verified": True,
                      "gameplay_status": "untested", "output": str(args.output)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
